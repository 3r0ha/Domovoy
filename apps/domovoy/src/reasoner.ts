const YES: readonly string[] = ['true', 'yes', 'да'];
const NO: readonly string[] = ['false', 'no', 'нет'];

/**
 * Ответ «да или нет» читается по первому слову. Проверка вхождением принимала
 * и «не true», то есть ровно противоположное сказанному. Разметку, кавычки и
 * знаки препинания модель ставит и там, где её просят отвечать одним словом.
 */
const yesOrNo = (answer: string): boolean | undefined => {
  const first = answer.trim().toLowerCase().replace(/[^a-zа-яё]/gu, ' ').trim().split(/\s+/u)[0] ?? '';

  if (YES.includes(first)) return true;
  if (NO.includes(first)) return false;

  return undefined;
};

/**
 * Объект JSON из текста ответа. Скобки считаются с учётом строк: модель
 * дописывает пояснение после объекта, и кусок «от первой скобки до последней»
 * тогда перестаёт разбираться.
 */
const objectIn = (raw: string): string | undefined => {
  const start = raw.indexOf('{');

  if (start < 0) return undefined;

  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let at = start; at < raw.length; at += 1) {
    const char = raw[at];

    if (escaped) escaped = false;
    else if (char === '\\') escaped = true;
    else if (char === '"') inString = !inString;
    else if (inString) continue;
    else if (char === '{') depth += 1;
    else if (char === '}' && --depth === 0) return raw.slice(start, at + 1);
  }

  return undefined;
};

/** Мелкие огрехи ответа: запятая перед скобкой и одинарные кавычки вместо двойных. */
const repaired = (text: string): string => {
  const commas = text.replace(/,\s*([}\]])/gu, '$1');

  return commas.includes('"') ? commas : commas.replace(/'/gu, '"');
};

/** Модель отвечает то объектом, то текстом с разметкой: достаём JSON из любого. */
const parse = (raw: string): ReasonedFields | undefined => {
  const found = objectIn(raw) ?? raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1);

  if (!found.startsWith('{')) return undefined;

  for (const text of [found, repaired(found)]) {
    try {
      const read: unknown = JSON.parse(text);

      if (read && typeof read === 'object' && !Array.isArray(read)) return read;
    } catch {
      continue;
    }
  }

  return undefined;
};

/** Ответ приходит либо в форме OpenAI, либо в форме Anthropic. */
const answerOf = (body: unknown): string | undefined => {
  const shape = body as {
    choices?: { message?: { content?: unknown } }[];
    content?: { text?: unknown }[];
  };

  const chat = shape.choices?.[0]?.message?.content;

  if (typeof chat === 'string') return chat;

  const block = shape.content?.[0]?.text;

  return typeof block === 'string' ? block : undefined;
};

