/**
 * Документы продукта на одном языке. Текст лежит рядом со словарями: он такая же
 * часть перевода, как строки интерфейса, и добавляется файлом на язык.
 */
export interface LegalText {
  /** Имя в адресе: `domovoy.homes/<slug>/`. */
  slug: string;
  title: string;
  /** Короткое имя для строки списка и кнопки меню. */
  short: string;
  /** Одна строка о документе: она стоит под названием и на сайте. */
  about: string;
  /** Текст разделами: заголовок и пункты. */
  parts: { heading: string; lines: string[] }[];
}

/** Подписи вокруг документа: они не часть текста, но идут на том же языке. */
export interface LegalNotes {
  /** Подпись редакции. Дата подставляется в `{date}`. */
  updated: string;
  /** Оговорка о языке: показывается на нерусской странице. */
  prevails: string;
  /** Название списка языков у переключателя. */
  languages: string;
}
