export const LEGAL_DOCUMENTS: readonly LegalDocument[] = [PRIVACY, TERMS];

/** Документ по имени из адреса. */
export const legalDocument = (slug: string): LegalDocument | undefined =>
  LEGAL_DOCUMENTS.find((document) => document.slug === slug);

/** Документ сплошным текстом: так он уходит в переписку и в файл. */
export const formatLegal = (document: LegalDocument): string =>
  [
    document.title,
    `Редакция от ${LEGAL_UPDATED}`,
    '',
    ...document.parts.flatMap((part) => [part.heading, ...part.lines, '']),
  ]
    .join('\n')
    .trim();

