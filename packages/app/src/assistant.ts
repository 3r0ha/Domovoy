/** Что человеку доступно в его роли. */
export const capabilitiesFor = (role: Role): Capability[] =>
  CAPABILITIES.filter((item) => !item.roles || item.roles.includes(role));

export interface AssistantAnswer {
  answer: string;
  /** Вопрос не о доме и не о продукте: помощник объяснил, чем занимается. */
  offTopic?: boolean;
  /** Куда идти в приложении. Пусто, если переход не нужен. */
  screen?: string;
  /** Название этого раздела: им подписана кнопка перехода. */
  title?: string;
  /** Та же возможность в переписке с ботом. */
  command?: string;
  /** Ответ собрала модель или подобрали ключевые слова. */
  by: 'model' | 'keywords';
}

/** Сколько знаков помощник отдаёт человеку: длинный ответ бабушка не прочитает. */
export const ANSWER_MAX_LENGTH = 400;

const QUESTION_MAX_LENGTH = 500;

/**
 * Подбор раздела по словам: так помощник работает и без модели. Выигрывает
 * самое длинное совпадение, иначе «принять заявку» у смены разошлось бы с
 * «заявкой» жильца и увело сотрудника в форму обращения.
 */
export const findCapability = (question: string, role: Role): Capability | undefined => {
  let best: { item: Capability; length: number } | undefined;

  for (const item of capabilitiesFor(role)) {
    const found = item.words.exec(question);

    if (!found) continue;
    if (best && found[0].length <= best.length) continue;

    best = { item, length: found[0].length };
  }

  return best?.item;
};

const plainAnswer = (question: string, role: Role): AssistantAnswer => {
  const found = findCapability(question, role);

  if (!found) {
    const list = CAPABILITIES.find((item) => item.screen === 'list');

    return {
      answer:
        'Не понял вопрос. Здесь можно сообщить о поломке, передать показания, посмотреть заявки ' +
        'и написать в управляющую организацию.',
      screen: 'list',
      ...(list ? { title: list.title } : {}),
      by: 'keywords',
    };
  }

  return {
    answer: `${found.title}: ${found.about}.`,
    screen: found.screen,
    title: found.title,
    ...(found.command ? { command: found.command } : {}),
    by: 'keywords',
  };
};

