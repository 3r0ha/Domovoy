/** Длинное тире модель ставит и там, где её просят не ставить: меняем на дефис. */
const dashless = (text: string): string => text.replace(/[—–]/g, '-');

/** Кавычки в ответе приводим к одним: модель ставит то лапки, то прямые. */
const quoted = (text: string): string => text.replace(/["'`]([^"'`]{1,60})["'`]/g, '«$1»');

/** Разметку модель иногда добавляет вопреки правилам: в переписке она видна звёздочками. */
const unmarked = (text: string): string => text.replace(/\*{1,3}([^*\n]+)\*{1,3}/gu, '$1').replace(/^#{1,6}\s*/gmu, '');

/**
 * Денежные суммы строки. Пробелы убираются до разбора: разряды модель отбивает
 * то обычным пробелом, то неразрывным, и одно и то же число иначе не совпадёт.
 */
const money = (text: string): string[] =>
  (text.replace(/\s/gu, '').match(/\d+[.,]\d{2}|\d{3,}/g) ?? []).map((value) => value.replace('.', ','));

/**
 * Суммы в ответе сверяются с фактами. Складывать долг с начислением модели
 * нельзя: человек решает по этой сумме, платить ему или спорить, а лишний
 * рубль в ответе стоит доверия ко всему продукту.
 */
export const groundedInMoney = (answer: string, facts: string): boolean => {
  const known = new Set(money(facts));

  return money(answer).every((value) => known.has(value));
};

/**
 * Подбор раздела по словам: так помощник работает и без модели. Выигрывает
 * самое длинное совпадение, иначе «принять заявку» у смены разошлось бы с
 * «заявкой» жильца и увело сотрудника в форму обращения.
 */
export const findCapability = (question: string, role: Role): Capability | undefined => {
  let best: { item: Capability; length: number } | undefined;

  for (const item of capabilitiesFor(role)) {
    const found = item.words.exec(question);

    if (!found) continue;
    if (best && found[0].length <= best.length) continue;

    best = { item, length: found[0].length };
  }

  return best?.item;
};

