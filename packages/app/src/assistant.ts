/**
 * Помощник в приложении и в переписке: короткий ответ и готовый переход.
 * Без модели отвечает подбором по словам, поэтому работает всегда.
 */
/** Что помощник отвечает на постороннюю просьбу. */
export const OFF_TOPIC =
  'Я помогаю только с домом и этим приложением: заявки, счётчики, квитанция, собрания, ' +
  'двери и вопросы в управляющую организацию. С остальным ответит человек из управляющей организации.';

export const askAssistant = async (
  deps: AppDeps,
  resident: Resident,
  question: string,
): Promise<AssistantAnswer> => {
  const asked = question.trim().slice(0, QUESTION_MAX_LENGTH);
  const plain = plainAnswer(asked, resident.role);
  const reasoner: Reasoner | undefined = deps.reasoner;

  if (asked.length === 0 || !reasoner?.assist) return plain;

  // Сначала отдельным вопросом проверяется, о доме ли речь. Так посторонняя
  // просьба не доходит до подсказки и не тратит ни ответа, ни доверия.
  const about = reasoner.onTopic ? await reasoner.onTopic(asked).catch(() => undefined) : undefined;

  // Даже с посторонней просьбой человека не оставляют ни с чем: разговор с
  // живым сотрудником идёт в поддержке, и кнопка туда есть всегда.
  if (about === false) {
    const support = CAPABILITIES.find((item) => item.screen === 'support');

    return {
      answer: OFF_TOPIC,
      offTopic: true,
      screen: 'support',
      ...(support ? { title: support.title, ...(support.command ? { command: support.command } : {}) } : {}),
      by: 'model',
    };
  }

  const sections = capabilitiesFor(resident.role).map((item) => ({
    screen: item.screen,
    title: item.title,
    about: item.about,
  }));

  const read = await reasoner
    .assist({
      question: asked,
      facts: await dossierFor(deps, resident),
      knowledge: knowledgeFor(resident.role),
      sections,
    })
    .catch(() => undefined);

  if (!read?.answer?.trim()) return plain;

  // Раздел, которого у роли нет, помощник не предлагает: кнопка вела бы в отказ.
  const screen = sections.some((item) => item.screen === read.screen) ? read.screen : undefined;
  const capability = CAPABILITIES.find((item) => item.screen === screen);

  return {
    answer: read.answer.trim().slice(0, ANSWER_MAX_LENGTH),
    ...(screen ? { screen } : {}),
    ...(capability?.title ? { title: capability.title } : {}),
    ...(capability?.command ? { command: capability.command } : {}),
    by: 'model',
  };
};
