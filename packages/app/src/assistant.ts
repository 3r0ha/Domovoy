export interface AssistantAnswer {
  answer: string;
  /** Вопрос не о доме и не о продукте: помощник объяснил, чем занимается. */
  offTopic?: boolean;
  /** Куда идти в приложении. Пусто, если переход не нужен. */
  screen?: string;
  /** Название этого раздела: им подписана кнопка перехода. */
  title?: string;
  /** Та же возможность в переписке с ботом. */
  command?: string;
  /** Ответ собрала модель или подобрали ключевые слова. */
  by: 'model' | 'keywords';
}

